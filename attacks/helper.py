# ── Key schedule ───────────────────────────────────────────────────────────────

def forward_key_schedule(key: bytes, n_rounds: int = 10) -> list:
    """Expand round-0 key into all round keys (flat list, 16*(n_rounds+1) bytes)."""
    rk = list(key)
    for i in range(4, 4 * (n_rounds + 1)):
        a0, a1, a2, a3 = rk[(i-1)*4:i*4]
        if i % 4 == 0:
            a0, a1, a2, a3 = SBOX[a1] ^ RCON[i // 4], SBOX[a2], SBOX[a3], SBOX[a0]
        b0, b1, b2, b3 = rk[(i-4)*4:(i-3)*4]
        rk.extend([a0^b0, a1^b1, a2^b2, a3^b3])
    return rk


def extract_round_key(key: bytes, round_num: int) -> bytes:
    """Extract a specific round key from the expanded schedule."""
    rk = forward_key_schedule(key)
    return bytes(rk[round_num*16:(round_num+1)*16])


def backward_key_schedule(round_key_10: bytes, n_rounds: int = 10) -> bytes:
    """Recover round-0 (original) key from round-10 key."""
    rk = list(round_key_10)
    for i in range(n_rounds, 0, -1):
        b12 = rk[12]^rk[8];  b13 = rk[13]^rk[9]
        b14 = rk[14]^rk[10]; b15 = rk[15]^rk[11]
        b8  = rk[8] ^rk[4];  b9  = rk[9] ^rk[5]
        b10 = rk[10]^rk[6];  b11 = rk[11]^rk[7]
        b4  = rk[4] ^rk[0];  b5  = rk[5] ^rk[1]
        b6  = rk[6] ^rk[2];  b7  = rk[7] ^rk[3]
        a0 = SBOX[b13]^RCON[i]; a1 = SBOX[b14]
        a2 = SBOX[b15];         a3 = SBOX[b12]
        b0 = a0^rk[0]; b1 = a1^rk[1]
        b2 = a2^rk[2]; b3 = a3^rk[3]
        rk = [b0,b1,b2,b3,b4,b5,b6,b7,b8,b9,b10,b11,b12,b13,b14,b15] + rk
    return bytes(rk[:16])

# ── Attack utilities ───────────────────────────────────────────────────────────

def verify_key(round_key_10: list, known_key: np.ndarray) -> bool:
    """True if backward_key_schedule(round_key_10) == known_key."""
    return list(backward_key_schedule(bytes(round_key_10))) == list(known_key)


def key_rank(scores: np.ndarray, correct_byte: int) -> int:
    """Rank of the correct key byte by score (1 = top guess, 256 = worst)."""
    return int(np.where(np.argsort(scores)[::-1] == correct_byte)[0][0]) + 1


def load_dataset(data_dir: str):
    """Load traces, plaintexts, ciphertexts, and meta.json from a dataset directory."""
    traces      = np.load(os.path.join(data_dir, 'traces.npy')).astype(np.float32)
    plaintexts  = np.load(os.path.join(data_dir, 'plaintexts.npy')).astype(np.uint8)
    ciphertexts = np.load(os.path.join(data_dir, 'ciphertexts.npy')).astype(np.uint8)

    known_key = None
    label     = data_dir
    meta_path = os.path.join(data_dir, 'meta.json')
    if os.path.exists(meta_path):
        import json
        with open(meta_path) as f:
            meta = json.load(f)
        known_key = np.array(meta['key'], dtype=np.uint8)
        label     = meta.get('label', data_dir)

    return traces, plaintexts, ciphertexts, known_key, label


def plots_dir(data_dir: str) -> str:
    """Return (and create) the plots/ subdirectory for a dataset."""
    p = os.path.join(data_dir, 'plots')
    os.makedirs(p, exist_ok=True)
    return p

# ── Plot style ─────────────────────────────────────────────────────────────────

STYLE = {
    'correct': '#2ecc71',   # green  — correct key hypothesis
    'wrong':   '#e74c3c',   # red    — wrong key hypothesis
    'neutral': '#3498db',   # blue   — neutral bars / reference lines
    'bg':      '#1a1a2e',   # dark background
    'grid':    '#2d2d4e',   # subtle grid
    'text':    '#ecf0f1',   # light text
}


def apply_dark_style(fig, axes):
    """Apply a consistent dark theme to a figure and its axes."""
    fig.patch.set_facecolor(STYLE['bg'])
    for ax in (axes if hasattr(axes, '__iter__') else [axes]):
        ax.set_facecolor(STYLE['bg'])
        ax.tick_params(colors=STYLE['text'])
        ax.xaxis.label.set_color(STYLE['text'])
        ax.yaxis.label.set_color(STYLE['text'])
        ax.title.set_color(STYLE['text'])
        for spine in ax.spines.values():
            spine.set_edgecolor(STYLE['grid'])
        ax.grid(True, color=STYLE['grid'], linewidth=0.5, alpha=0.7)
